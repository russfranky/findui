# ---------------------------------------------------------------------------
# Flows. A FindUI flow is a graph, not a filmstrip: states are nodes, edges
# carry the per-step action, branch points are explicit, and every flow has
# success criteria plus a trajectory record (the capture spec example).
# ---------------------------------------------------------------------------

def _state(state_id, screen_id, label, flags=None):
    return {"state_id": state_id, "screen_id": screen_id, "label": label,
            "flags": flags or []}


def _edge(from_state, to_state, action_type, target, x, y, condition=None, text=None):
    action = {"type": action_type, "target_element": target,
              "coordinates": {"x": x, "y": y, "scale": "0-1000 relative"}}
    if text is not None:
        action["text"] = text
    edge = {"from_state": from_state, "to_state": to_state, "action": action}
    if condition:
        edge["condition"] = condition
    return edge


def _traj_step(index, state_id, screen_ref, elements, action, outcome, a11y):
    return {
        "step_index": index,
        "state_id": state_id,
        "screenshot_ref": screen_ref,
        "elements": [{"label": label, "role": role,
                      "bbox": {"x_min": b[0], "y_min": b[1], "x_max": b[2], "y_max": b[3]}}
                     for label, role, b in elements],
        "action": action,
        "accessibility_snippet": a11y,
        "outcome_label": outcome,
    }


def _flow(id, name, app_name, platform, vertical, version, captured, states,
          edges, branch_points, entry, exits, criteria, trajectory,
          creator=None, actions=None):
    item = {
        "id": id,
        "kind": "flow",
        "name": name,
        "app_name": app_name,
        "platform": platform,
        "vertical": vertical,
        "actions": actions or sorted({e["action"]["target_element"] for e in edges}),
        "screen_count": len(states),
        "states": states,
        "edges": edges,
        "branch_points": branch_points,
        "entry_state": entry,
        "exit_states": exits,
        "success_criteria": criteria,
        "trajectory": {"flow_id": id, "recorded_by": "prototype seed author",
                       "steps": trajectory},
        "findui_url": f"https://findui.com/flows/{id}",
        "app_version": version,
        "captured_at": captured,
    }
    item.update(creator or CAPTURE_TEAM)
    return item


